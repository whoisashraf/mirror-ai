create policy "merchant storefronts are readable" on public.merchants for select using (true);
create policy "merchant owners insert own store" on public.merchants for insert to authenticated with check (owner_user_id = auth.uid());
create policy "merchant owners update own store" on public.merchants for update to authenticated using (owner_user_id = auth.uid()) with check (owner_user_id = auth.uid());
create policy "merchant owners delete own store" on public.merchants for delete to authenticated using (owner_user_id = auth.uid());

create policy "active products are public" on public.products for select using (is_active or exists(select 1 from public.merchants m where m.id=merchant_id and m.owner_user_id=auth.uid()));
create policy "owners insert products" on public.products for insert to authenticated with check (exists(select 1 from public.merchants m where m.id=merchant_id and m.owner_user_id=auth.uid()));
create policy "owners update products" on public.products for update to authenticated using (exists(select 1 from public.merchants m where m.id=merchant_id and m.owner_user_id=auth.uid()));
create policy "owners delete products" on public.products for delete to authenticated using (exists(select 1 from public.merchants m where m.id=merchant_id and m.owner_user_id=auth.uid()));

create policy "shoppers manage own profile" on public.shopper_profiles for all to authenticated using (user_id=auth.uid()) with check (user_id=auth.uid());
create policy "shoppers manage own image rows" on public.shopper_images for all to authenticated using (user_id=auth.uid()) with check (user_id=auth.uid());

create policy "shopper or merchant reads generation" on public.try_on_generations for select to authenticated using (shopper_user_id=auth.uid() or exists(select 1 from public.merchants m where m.id=merchant_id and m.owner_user_id=auth.uid()));
create policy "shopper or merchant reads generation products" on public.try_on_products for select to authenticated using (exists(select 1 from public.try_on_generations g join public.merchants m on m.id=g.merchant_id where g.id=generation_id and (g.shopper_user_id=auth.uid() or m.owner_user_id=auth.uid())));

create policy "shopper or merchant reads conversations" on public.conversations for select to authenticated using (shopper_user_id=auth.uid() or exists(select 1 from public.merchants m where m.id=merchant_id and m.owner_user_id=auth.uid()));
create policy "conversation participants read messages" on public.messages for select to authenticated using (exists(select 1 from public.conversations c join public.merchants m on m.id=c.merchant_id where c.id=conversation_id and (c.shopper_user_id=auth.uid() or m.owner_user_id=auth.uid())));

create policy "merchant owner reads analytics" on public.analytics_events for select to authenticated using (exists(select 1 from public.merchants m where m.id=merchant_id and m.owner_user_id=auth.uid()));

-- Private storage buckets. Public product assets can still be read directly.
insert into storage.buckets (id,name,public) values
 ('product-images','product-images',true),
 ('shopper-images','shopper-images',false),
 ('try-on-results','try-on-results',false),
 ('merchant-assets','merchant-assets',true)
on conflict (id) do update set public=excluded.public;

create policy "public reads product images" on storage.objects for select using (bucket_id='product-images');
create policy "owners upload product images" on storage.objects for insert to authenticated with check (bucket_id='product-images' and exists(select 1 from public.merchants m where m.owner_user_id=auth.uid() and m.id::text=(storage.foldername(name))[1]));
create policy "owners manage product images" on storage.objects for update to authenticated using (bucket_id='product-images' and exists(select 1 from public.merchants m where m.owner_user_id=auth.uid() and m.id::text=(storage.foldername(name))[1]));
create policy "owners delete product images" on storage.objects for delete to authenticated using (bucket_id='product-images' and exists(select 1 from public.merchants m where m.owner_user_id=auth.uid() and m.id::text=(storage.foldername(name))[1]));

create policy "shopper uploads own source images" on storage.objects for insert to authenticated with check (bucket_id='shopper-images' and (storage.foldername(name))[1]=auth.uid()::text);
create policy "shopper reads own source images" on storage.objects for select to authenticated using (bucket_id='shopper-images' and (storage.foldername(name))[1]=auth.uid()::text);
create policy "shopper deletes own source images" on storage.objects for delete to authenticated using (bucket_id='shopper-images' and (storage.foldername(name))[1]=auth.uid()::text);
create policy "shopper reads own tryon results" on storage.objects for select to authenticated using (bucket_id='try-on-results' and (storage.foldername(name))[1]=auth.uid()::text);

create policy "public reads merchant assets" on storage.objects for select using (bucket_id='merchant-assets');
create policy "owners upload merchant assets" on storage.objects for insert to authenticated with check (bucket_id='merchant-assets' and exists(select 1 from public.merchants m where m.owner_user_id=auth.uid() and m.id::text=(storage.foldername(name))[1]));
